function curLang(){return localStorage.getItem('df_lang')||'hi'}
function T(k){const d=I18N[k];return d?(d[curLang()]||d.hi):k}
function applyLang(){
 document.querySelectorAll('[data-i18n]').forEach(el=>{el.innerHTML=T(el.dataset.i18n)});
 document.querySelectorAll('[data-i18n-ph]').forEach(el=>{el.placeholder=T(el.dataset.i18nPh)});
 document.documentElement.lang=curLang()==='hi'?'hi':'en';
 const b=document.getElementById('langToggle');if(b)b.textContent=curLang()==='hi'?'EN':'हिं';
 document.title=document.title; 
}
document.addEventListener('DOMContentLoaded',function(){
 applyLang();
 const b=document.getElementById('langToggle');
 if(b)b.addEventListener('click',function(){localStorage.setItem('df_lang',curLang()==='hi'?'en':'hi');location.reload();});
});
